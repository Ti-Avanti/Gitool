function remoteSyncLabelZh(state: RemoteSyncState): string {
  if (state === "synced") {
    return "已同步";
  }
  if (state === "ahead") {
    return "待推送";
  }
  if (state === "behind") {
    return "需拉取";
  }
  if (state === "diverged") {
    return "需处理分叉";
  }
  if (state === "no-upstream") {
    return "未设置上游";
  }
  return "未知";
}

function remoteSyncLabelEn(state: RemoteSyncState): string {
  if (state === "synced") {
    return "Synced";
  }
  if (state === "ahead") {
    return "Push needed";
  }
  if (state === "behind") {
    return "Pull needed";
  }
  if (state === "diverged") {
    return "Diverged";
  }
  if (state === "no-upstream") {
    return "No upstream";
  }
  return "Unknown";
}

function pullModeLabelZh(mode: PullMode): string {
  if (mode === "ff-only") {
    return "仅快进";
  }
  if (mode === "rebase") {
    return "变基";
  }
  return "合并";
}

function pullModeLabelEn(mode: PullMode): string {
  if (mode === "ff-only") {
    return "Fast-forward only";
  }
  if (mode === "rebase") {
    return "Rebase";
  }
  return "Merge";
}
